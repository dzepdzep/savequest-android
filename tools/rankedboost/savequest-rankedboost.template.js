    if(!primary&&backup){
      const copy=bytes.slice();
      for(const [start,end,from] of [[0x2009,0x222e,0x15c7],[0x222f,0x23d8,0x3d96],[0x23d9,0x2855,0x0c6b],[0x2856,0x2889,0x7e39],[0x288a,0x2d68,0x10e8]])
        copy.set(bytes.slice(from,from+end-start+1),start);
      bytes=copy;
    }
    if(!bytes.slice(0x200b,0x2016).some(x=>x!==0&&x!==0x50))throw Error('Trainer name missing from SRAM.');
    const caught=[];
    for(let i=0;i<251;i++)if(bytes[0x2a4c+(i>>3)]&(1<<(i&7)))caught.push(GAME.species[i]);
